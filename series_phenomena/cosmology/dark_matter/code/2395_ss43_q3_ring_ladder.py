def spline_V(rr, prof, scale):
    lr, lp = np.log(rr), np.log(np.maximum(prof, 1e-300))

    def V(x):
        if x <= rr[0]:
            return scale * prof[0]
        if x >= rr[-1]:
            return scale * prof[-1] * math.exp(-(x - rr[-1]) / RS) * rr[-1] / x
        return scale * math.exp(np.interp(math.log(x), lr, lp))
    return V


